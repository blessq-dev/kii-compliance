"""Папки программы.

Программа читает данные из своей папки (база правил, тестовый набор) и пишет файлы,
которые создаёт пользователь (перечень объектов, журналы эксперимента, добавленные
редакции пакетов правил), в папку данных пользователя.

При обычном запуске (streamlit run app.py) обе папки — внутри проекта: rules/ и data/.
Собранная программа (exe, см. launcher.py) распаковывается во временную папку, поэтому
папку данных пользователя ей задаёт переменная окружения KII_USER_DIR — папка рядом с exe.
"""

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # корень проекта (или распакованной программы)
RULES_DIR = ROOT / "rules"                     # база правил, поставляемая с программой
DATA_DIR = ROOT / "data"                       # тестовый набор объектов (только чтение)

USER_DIR = Path(os.environ.get("KII_USER_DIR") or DATA_DIR)  # файлы пользователя
# Редакции пакетов правил, добавленные пользователем. При обычном запуске — та же папка rules/.
USER_RULES_DIR = USER_DIR / "rules" if os.environ.get("KII_USER_DIR") else RULES_DIR
